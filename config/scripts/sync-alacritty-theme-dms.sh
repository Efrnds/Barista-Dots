#!/usr/bin/env bash
set -euo pipefail

DMS_COLORS_JSON="$HOME/.cache/DankMaterialShell/dms-colors.json"
ALACRITTY_COLORS="$HOME/.config/alacritty/colors.toml"

if [[ ! -f "$DMS_COLORS_JSON" ]]; then
  echo "sync-alacritty-theme-dms: missing $DMS_COLORS_JSON" >&2
  exit 1
fi

python3 - <<'PY' "$DMS_COLORS_JSON" "$ALACRITTY_COLORS"
import json, sys
from pathlib import Path

src = Path(sys.argv[1])
out = Path(sys.argv[2])
data = json.loads(src.read_text(encoding="utf-8"))
colors_dark = data["colors"]["dark"]
dank16 = data["dank16"]

def hx(c: str) -> str:
    c = c.lstrip("#").upper()
    return f"#{c}"

def dank(i: int) -> str:
    return hx(dank16[f"color{i}"]["dark"])

bg = hx(colors_dark["background"])
fg = hx(colors_dark["on_background"])
sel = hx(colors_dark.get("inverse_primary", colors_dark.get("primary", "#3E4953")))
regular = [dank(i) for i in range(8)]
bright = [dank(i) for i in range(8, 16)]

out.parent.mkdir(parents=True, exist_ok=True)
out.write_text(
    "\n".join(
        [
            "# Auto-generated by DMS sync",
            "# Do not edit manually - changes will be overwritten",
            "",
            "[colors.primary]",
            f'foreground = "{fg}"',
            f'background = "{bg}"',
            "",
            "[colors.normal]",
            f'black   = "{regular[0]}"',
            f'red     = "{regular[1]}"',
            f'green   = "{regular[2]}"',
            f'yellow  = "{regular[3]}"',
            f'blue    = "{regular[4]}"',
            f'magenta = "{regular[5]}"',
            f'cyan    = "{regular[6]}"',
            f'white   = "{regular[7]}"',
            "",
            "[colors.bright]",
            f'black   = "{bright[0]}"',
            f'red     = "{bright[1]}"',
            f'green   = "{bright[2]}"',
            f'yellow  = "{bright[3]}"',
            f'blue    = "{bright[4]}"',
            f'magenta = "{bright[5]}"',
            f'cyan    = "{bright[6]}"',
            f'white   = "{bright[7]}"',
            "",
            "[colors.selection]",
            f'text       = "{fg}"',
            f'background = "{sel}"',
            "",
        ]
    )
    + "\n",
    encoding="utf-8",
)
PY

chmod 0644 "$ALACRITTY_COLORS" || true
